# backupctl -- back up this host now, list its snapshots, and restore one
# service from restic without hand-typing paths, owners or unit names.
#
# The host's settings (BACKUPCTL_*, DB, UNIT, CERTS) are injected above this
# file by modules/infra/backup.nix. Runs as root (just backup/snapshots/restore
# call it over ssh -t with sudo).

usage() {
  cat >&2 <<EOF
Usage:
  backupctl backup                        run the nightly backup now
  backupctl snapshots                     list this host's snapshots
  backupctl list                          services this host can restore
  backupctl restore <service> [<snapshot>] [--yes]
                                          put one service back (default: latest)

After a rebuild, the latest snapshot may already hold the fresh, empty data:
pick the last one from before the rebuild (backupctl snapshots).
EOF
  exit 2
}
die() {
  echo "backupctl: $*" >&2
  exit 1
}

[ "$(id -u)" = 0 ] || die "run as root (sudo backupctl ...)"

export RESTIC_REPOSITORY="$BACKUPCTL_REPOSITORY"
export RESTIC_PASSWORD_FILE="$BACKUPCTL_PASSWORD_FILE"
export RESTIC_CACHE_DIR="$BACKUPCTL_CACHE_DIR"
# The B2 key ID and key
set -a
# shellcheck disable=SC1090
. "$BACKUPCTL_ENV_FILE"
set +a

services() {
  printf '%s\n' "${!DB[@]}" acme | sort
}

confirm() {
  [ "$yes" = 1 ] && return 0
  local answer
  read -r -p "Go ahead? [y/N] " answer
  [[ $answer == [yY]* ]] || die "nothing changed"
}

# The snapshot's short ID and time, refusing anything that isn't this host's
resolve() {
  local json host filter=()
  # restic applies --host to latest only, and ignores it beside an ID
  [ "$1" = latest ] && filter=(--host "$BACKUPCTL_HOST")
  json=$(restic snapshots "${filter[@]}" --json "$1" 2>/dev/null) ||
    die "no snapshot $1 for $BACKUPCTL_HOST"
  snap_id=$(jq -er '.[0].short_id' <<<"$json") || die "no snapshot $1 for $BACKUPCTL_HOST"
  host=$(jq -r '.[0].hostname' <<<"$json")
  [ "$host" = "$BACKUPCTL_HOST" ] || die "snapshot $snap_id is $host's, not $BACKUPCTL_HOST's"
  snap_time=$(jq -er '.[0].time' <<<"$json")
  echo "Snapshot $snap_id, taken $(date -d "$snap_time" '+%F %T %Z')"
  if [ "$(date -d "$snap_time" +%s)" -gt "$(date -d "$(uptime -s)" +%s)" ]; then
    echo "Note: it's newer than this boot ($(uptime -s)). After a rebuild, that"
    echo "means fresh data; the one you want is probably older."
  fi
}

do_backup() {
  local since
  since=$(date '+%F %T')
  echo "Running $BACKUPCTL_UNIT (a minute or so)..."
  if systemctl start "$BACKUPCTL_UNIT"; then
    journalctl -u "$BACKUPCTL_UNIT" --since "$since" -o cat |
      grep -E 'snapshot .* saved|Added to the repository|no errors were found' || true
  else
    journalctl -u "$BACKUPCTL_UNIT" --since "$since" -o cat | tail -20
    die "$BACKUPCTL_UNIT failed"
  fi
}

restore_db() {
  local name=$1 db=${DB[$1]} unit=${UNIT[$1]}
  local staged=$BACKUPCTL_STAGING/$name.sqlite
  local before=$BACKUPCTL_STAGING/$name.before-restore.sqlite
  local file mode check
  restic restore "$snap_id" --target "$work" --include "$staged" >/dev/null
  file=$work$staged
  [ -f "$file" ] || die "snapshot $snap_id has no $staged"
  check=$(sqlite3 "$file" 'PRAGMA integrity_check')
  [ "$check" = ok ] || die "the restored $name database fails integrity_check: $check"

  echo "Restored copy: $(stat -c %s "$file") bytes, integrity ok"
  if [ -f "$db" ]; then
    echo "Live database: $(stat -c %s "$db") bytes, changed $(date -r "$db" '+%F %T %Z')"
  fi
  echo "This stops $unit, replaces $db and starts it again."
  confirm

  mode=600
  if [ -f "$db" ]; then
    mode=$(stat -c %a "$db")
    sqlite3 "$db" ".backup $before"
    echo "Kept the live database as $before"
  fi
  systemctl stop "$unit"
  rm -f "$db-wal" "$db-shm"
  install -m "$mode" "$file" "$db"
  # Its directory's owner: right for fixed users, and the only way to name a
  # DynamicUser's
  chown --reference="$(dirname "$db")" "$db"
  systemctl start "$unit"
  sleep 3
  if ! systemctl is-active --quiet "$unit"; then
    journalctl -u "$unit" -n 10 -o cat --no-pager
    die "$unit didn't come back; the previous database is $before"
  fi
  echo "$unit is running on the restored database."
}

cert_expiry() {
  [ -f "$1" ] && openssl x509 -noout -enddate -in "$1" | cut -d= -f2
}

restore_acme() {
  local src=$work/var/lib/acme cert
  restic restore "$snap_id" --target "$work" --include /var/lib/acme >/dev/null
  [ -d "$src/.lego/accounts" ] || die "snapshot $snap_id has no ACME account"
  for cert in "${CERTS[@]}"; do
    echo "$cert: restored certificate expires $(cert_expiry "$src/$cert/cert.pem" || echo '(none)'),"
    echo "  live one $(cert_expiry "/var/lib/acme/$cert/cert.pem" || echo '(none)')"
  done
  echo "This replaces the ACME account and certificates and reloads nginx."
  confirm

  # Regenerated by acme-setup, which doesn't re-own a restored copy
  rm -rf "$src/.minica"
  cp -a "$src/." /var/lib/acme/
  # acme-setup re-owns the account and certificate directories
  systemctl restart acme-setup.service
  for cert in "${CERTS[@]}"; do
    systemctl restart "acme-$cert.service"
  done
  systemctl reload nginx.service
  echo "Restored; nginx serves the restored certificates."
}

cmd=${1:-}
[ -n "$cmd" ] || usage
shift
case $cmd in
backup)
  [ $# = 0 ] || usage
  do_backup
  ;;
snapshots)
  [ $# = 0 ] || usage
  restic snapshots --host "$BACKUPCTL_HOST"
  ;;
list)
  [ $# = 0 ] || usage
  services
  ;;
restore)
  yes=0
  args=()
  for arg; do
    case $arg in
    --yes) yes=1 ;;
    -*) usage ;;
    *) args+=("$arg") ;;
    esac
  done
  [ "${#args[@]}" -ge 1 ] && [ "${#args[@]}" -le 2 ] || usage
  service=${args[0]}
  services | grep -qx "$service" || die "no service $service here; try: $(services | paste -sd' ')"
  work=$(mktemp -d /var/tmp/backupctl.XXXXXX)
  trap 'rm -rf "$work"' EXIT
  resolve "${args[1]:-latest}"
  if [ "$service" = acme ]; then
    restore_acme
  else
    restore_db "$service"
  fi
  ;;
*) usage ;;
esac
